import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadSurface } from "@hermesd/contracts";

/**
 * Generates the DDL of the preserved upstream tables from
 * `contracts/upstream/state-schema.json`. The statements are copied as they
 * are, so column names, types, defaults and keys stay byte-identical.
 *
 * Run it with `bun packages/session-actor/src/generate-ddl.ts` after the
 * extractor ran again (for example after an upstream pin bump). A test fails
 * when the committed `upstream-ddl.ts` is not what this function renders.
 */

interface SchemaTable {
  name: string;
  kind: string;
  sql: string;
}

export interface SchemaSurface {
  schema_version: number | null;
  upstream_commit: string | null;
  tables: SchemaTable[];
}

/** The tables this port keeps, and the actor that owns each (guide 2.4, table-decisions.json). */
export const PRESERVED_TABLES = {
  session: ["system_prompts", "sessions", "messages", "session_model_usage", "worker_executions", "worker_receipts"],
  profile: ["conversation_generations", "state_meta", "schema_version"],
} as const;

export function renderUpstreamDdl(surface: SchemaSurface = loadSurface<SchemaSurface>("state-schema")): string {
  const out: string[] = [
    "// GENERATED by src/generate-ddl.ts from contracts/upstream/state-schema.json. Do not edit.",
    "// The statements are upstream's own CREATE TABLE statements, copied without change.",
    "",
    `export const UPSTREAM_SCHEMA_VERSION = ${String(surface.schema_version)};`,
    `export const UPSTREAM_COMMIT = ${JSON.stringify(surface.upstream_commit)};`,
    "",
  ];
  const render = (doc: string, constName: string, names: readonly string[]): void => {
    out.push(`/** ${doc}, in creation order (a table comes after the tables it refers to). */`);
    out.push(`export const ${constName}: Readonly<Record<string, string>> = {`);
    for (const name of names) {
      const t = surface.tables.find((x) => x.name === name && x.kind === "table");
      if (!t) throw new Error(`upstream table ${name} is not in state-schema.json`);
      out.push(`  ${name}: ${JSON.stringify(t.sql)},`);
    }
    out.push("};", "");
  };
  render("Tables of the session actor", "SESSION_UPSTREAM_DDL", PRESERVED_TABLES.session);
  render("Tables of the profile actor", "PROFILE_UPSTREAM_DDL", PRESERVED_TABLES.profile);
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("./upstream-ddl.ts", import.meta.url), renderUpstreamDdl());
  process.stdout.write("wrote upstream-ddl.ts\n");
}
