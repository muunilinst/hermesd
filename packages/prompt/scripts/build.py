# Writes the two generated TypeScript text files from the JSON/TS pieces of
# extract.py and templ.py. Static data only.
import json, re, sys
import os
G = os.path.dirname(os.path.abspath(__file__)) + "/"
OUTDIR = sys.argv[1]
d = json.load(open(G + "consts.json", encoding="utf-8"))
tpl = open(G + "templ.ts", encoding="utf-8").read()


def js(v):
    return json.dumps(v, ensure_ascii=False, indent=2)


def const(name, v, src, export_name=None):
    n = export_name or name.lstrip("_")
    return f"/** Upstream {src}:{name}. */\nexport const {n} = {js(v)};\n"


pb = d["pb"]
lines = [
    "// GENERATED by scripts/build.py from the pinned upstream source (a9ff9799).",
    "// The strings are read with a parser, not by running upstream code. Do not edit by hand.",
    "",
]
for k in [
    "DEFAULT_AGENT_IDENTITY", "HERMES_AGENT_HELP_GUIDANCE", "HERMES_AGENT_HELP_GUIDANCE_NO_SKILLS",
    "SESSION_SEARCH_GUIDANCE", "SKILLS_GUIDANCE", "TOOL_USE_ENFORCEMENT_GUIDANCE", "TOOL_USE_ENFORCEMENT_MODELS",
    "EXECUTION_GUIDANCE_MODELS", "TASK_COMPLETION_GUIDANCE", "PARALLEL_TOOL_CALL_GUIDANCE",
    "OPENAI_MODEL_EXECUTION_GUIDANCE", "GOOGLE_MODEL_OPERATIONAL_GUIDANCE", "STEER_MARKER_OPEN",
    "STEER_MARKER_CLOSE", "STEER_CHANNEL_NOTE", "TELEGRAM_RICH_MESSAGES_HINT", "WSL_ENVIRONMENT_HINT",
    "RUNTIME_ENVIRONMENT_HEADING", "RUNTIME_ENVIRONMENT_END", "CONTEXT_FILE_MAX_CHARS",
]:
    lines.append(const(k, pb[k], "agent/prompt_builder.py"))
lines.append(const("PLATFORM_HINTS", pb["PLATFORM_HINTS"], "agent/prompt_builder.py"))
lines.append(const("_EXECUTION_GUIDANCE_LINE_TOOLS", pb["_EXECUTION_GUIDANCE_LINE_TOOLS"], "agent/prompt_builder.py", "EXECUTION_GUIDANCE_LINE_TOOLS"))
lines.append(const("_BACKEND_FALLBACK_DESCRIPTIONS", pb["_BACKEND_FALLBACK_DESCRIPTIONS"], "agent/prompt_builder.py", "BACKEND_FALLBACK_DESCRIPTIONS"))
open(OUTDIR + "/src/upstream-text.ts", "w", encoding="utf-8").write("\n".join(lines))

cc, pr, cm = d["cc"], d["pr"], d["cm"]
out = [
    "// GENERATED by scripts/build.py from the pinned upstream source (a9ff9799).",
    "// The strings are read with a parser, not by running upstream code. Do not edit by hand.",
    "",
]
for k in ["HISTORICAL_TASK_HEADING", "SUMMARY_PREFIX", "LEGACY_SUMMARY_PREFIX", "_NO_USER_TASK_SENTINEL",
          "COMPRESSION_CONTINUATION_USER_CONTENT", "_SUMMARY_END_MARKER", "_MERGED_PRIOR_CONTEXT_HEADER",
          "_MERGED_SUMMARY_DELIMITER", "_PRUNED_TOOL_PLACEHOLDER", "_COMPRESSION_NOTE"]:
    out.append(const(k, cc[k], "agent/context_compressor.py"))
out.append(const("_SECTION_INSTRUCTIONS", cc["_SECTION_INSTRUCTIONS"], "agent/context_compressor.py", "SECTION_INSTRUCTIONS_BY_FLAG"))
for k in ["UNVERIFIED_SECTION_HEADING", "EPISTEMIC_STANCE_RULE", "UNVERIFIED_HYPOTHESES_SECTION"]:
    out.append(const(k, pr[k], "agent/context_compressor_prompt_rules.py"))
out.append(const("_ELISION_MARKER_TEMPLATE", cm["_ELISION_MARKER_TEMPLATE"], "agent/compression_marker.py"))
out.append('export const PRUNED_SKILLS_SECTION_HEADING = "## Pruned Skills";\n')
out.append("export interface SectionInstructions {\n  language: string;\n  historical_task: string;\n  goal: string;\n  constraints: string;\n  resolved_questions: string;\n}\n")


def grab(name):
    m = re.search(r"export const " + name + r" = (.*?);\n\n", tpl + "\n\n", re.S)
    return m.group(1)


out.append("""/** Upstream agent/context_compressor.py:ContextCompressor._summary_template_sections (the f-string). */
export function templateSectionsText(
  section: SectionInstructions,
  summaryBudgetTotal: number,
  sessionLogSection: string,
  temporalAnchoringRule: string,
): string {
  return """ + grab("TEMPLATE_SECTIONS_EXPR") + """;
}

/** Upstream ..._build_summary_prompt, the iterative-update form. */
export function iterativePromptText(
  preamble: string,
  boundedPreviousSummary: string,
  contentToSummarize: string,
  memorySection: string,
  templateSections: string,
): string {
  return """ + grab("PROMPT_0") + """;
}

/** Upstream ..._build_summary_prompt, the first-summary form. */
export function freshPromptText(
  preamble: string,
  contentToSummarize: string,
  memorySection: string,
  templateSections: string,
): string {
  return """ + grab("PROMPT_1") + """;
}

/** Upstream ..._build_summary_prompt, the focus-topic addition. */
export function focusPromptText(focusTopic: string): string {
  return """ + grab("PROMPT_2") + """;
}

/** Upstream ContextCompressor._temporal_anchoring_rule. "" when the date is unknown. */
export function temporalAnchoringText(todayStr: string): string {
  if (!todayStr) return "";
  return """ + grab("TEMPORAL_0") + """;
}
""")
open(OUTDIR + "/src/compress/upstream-text.ts", "w", encoding="utf-8").write("\n".join(out))
print("written")
